import { chromium, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1100, height: 900 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://localhost:4173/');
  const primary = page.locator('.hero .btn');
  await primary.hover();
  await expect(primary).toHaveAttribute('data-glass-active', 'true');
  const bounds = await primary.boundingBox();
  await page.mouse.move(bounds.x + 14, bounds.y + 18);
  await expect.poll(() => primary.evaluate(el => parseFloat(el.style.getPropertyValue('--glass-x')))).toBeCloseTo(14, 0);
  await page.mouse.move(bounds.x + bounds.width - 18, bounds.y + 18);
  await expect.poll(() => primary.evaluate(el => parseFloat(el.style.getPropertyValue('--glass-x')))).toBeCloseTo(bounds.width - 18, 0);
  await page.mouse.down();
  await expect(primary).toHaveAttribute('data-glass-pressed', 'true');
  await page.mouse.move(5, 5);
  await page.mouse.up();
  await expect(primary).not.toHaveAttribute('data-glass-pressed', 'true');
  await page.getByRole('button', { name: 'Từ điển của bạn', exact: true }).click();
  const search = page.getByRole('searchbox');
  await search.fill('server');
  await expect(search).toHaveValue('server');
  await expect(page.locator('.word-row').first()).toBeVisible();
  await page.locator('.word-row').first().hover();
  await expect(page.locator('.word-row').first()).toHaveAttribute('data-glass-active', 'true');
  await page.getByRole('button', { name: 'Luyện dịch', exact: true }).click();
  await page.locator('textarea').first().fill('Bản dịch vẫn nhập bình thường.');
  await expect(page.locator('textarea').first()).toHaveValue('Bản dịch vẫn nhập bình thường.');
  await page.getByRole('button', { name: 'Xem đáp án tham khảo' }).first().click();
  await expect(page.locator('.translation-reference').first()).toBeVisible();
  await page.getByRole('button', { name: 'Đề thi', exact: true }).click();
  await page.getByRole('button', { name: 'Tạo đề trộn & bắt đầu' }).click();
  await page.locator('.exam-matching select').first().selectOption({ label: 'B' });
  await expect(page.locator('.exam-matching select').first().locator('option:checked')).toHaveText('B');
  const answer = page.locator('.exam-options label').first();
  await answer.scrollIntoViewIfNeeded();
  await page.waitForTimeout(100);
  await answer.hover();
  await expect(answer).toHaveAttribute('data-glass-active', 'true');
  await answer.click();
  await expect(answer.getByRole('radio')).toBeChecked();
  for (const width of [320, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  }
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const submit = page.getByRole('button', { name: 'Nộp bài', exact: true });
  await submit.scrollIntoViewIfNeeded();
  const button = await submit.boundingBox();
  await page.mouse.move(button.x + button.width / 2, button.y + button.height / 2);
  await page.mouse.down();
  await expect(submit).toHaveCSS('transform', 'none');
  await page.mouse.move(5, 5); await page.mouse.up();
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Tổng quan', exact: true }).click();
  await mkdir('qa', { recursive: true });
  await page.screenshot({ path: 'qa/global-glass-home.png' });
  const touch = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  await touch.goto('http://localhost:4173/');
  const touchButton = touch.locator('.hero .btn');
  const box = await touchButton.boundingBox();
  const cdp = await touch.context().newCDPSession(touch);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: box.x + 40, y: box.y + 20, id: 1 }] });
  await expect(touchButton).toHaveAttribute('data-glass-input', 'touch');
  await expect(touchButton).toHaveAttribute('data-glass-pressed', 'true');
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchCancel', touchPoints: [] });
  await expect(touchButton).not.toHaveAttribute('data-glass-pressed', 'true');
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 200, y: 550, id: 2 }] });
  for (const y of [500, 420, 320]) await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 200, y, id: 2 }] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await expect.poll(() => touch.evaluate(() => scrollY)).toBeGreaterThan(20);
  await cdp.detach(); await touch.close();
  expect(errors).toEqual([]);
  console.log('Global glass passed: moving reflections, press/release, dictionary, translation inputs, exam matching/radios, reduced motion, responsive widths.');
} finally { await browser.close(); }
