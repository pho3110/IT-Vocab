import fs from 'node:fs/promises';
import { units as existingUnits } from '../src/data.js';

const rows = JSON.parse(await fs.readFile('content/workbook-extracted.json', 'utf8'));
const legacy = JSON.parse(await fs.readFile('content/legacy-words.json', 'utf8'));
const translations = new Map((await fs.readFile('content/translations.txt', 'utf8')).trim().split('\n').map(line => {
  const [lesson, term, meaning] = line.trim().split('|');
  if (!lesson || !term || !meaning) throw new Error(`Invalid translation: ${line}`);
  return [`${lesson}:${term}`, meaning];
}));
const aliases = { 'lock (someone) out of (something)': 'lock someone out' };
const used = new Set(), allWords = [];
for (const row of rows) {
  const term = aliases[row.term] ?? row.term;
  const old = legacy.find(word => word.lessonId === row.lessonId && word.term === term)
    ?? legacy.find(word => word.term === term && !used.has(word.id));
  const meaning = translations.get(`${row.lessonId}:${row.term}`) ?? old?.meaning;
  if (!meaning) throw new Error(`Missing translation: ${row.lessonId}:${row.term}`);
  const id = old?.id ?? `${row.lessonId}-wb-${row.page}-${allWords.filter(w => w.lessonId === row.lessonId).length + 1}`;
  if (used.has(id)) throw new Error(`Duplicate ID: ${id}`);
  used.add(id);
  allWords.push({ id, unitId: Number(row.lessonId[0]), lessonId: row.lessonId, term: row.term, partOfSpeech: row.partOfSpeech, meaning, definition: row.definition, source: 'workbook', sourcePage: row.page });
}
// Keep the former supplemental RAM card so its saved progress/bookmark survives.
for (const old of legacy.filter(word => !used.has(word.id))) {
  if (old.term !== 'RAM') throw new Error(`Legacy card not migrated: ${old.term}`);
  allWords.push({ ...old, partOfSpeech: 'n', source: 'supplemental', sourcePage: null });
}
const units = existingUnits.map(unit => ({ ...unit, lessons: unit.lessons.map(lesson => ({ ...lesson, words: allWords.filter(word => word.lessonId === lesson.id) })) }));
const counts = Object.fromEntries(units.flatMap(u => u.lessons).map(l => [l.id, l.words.filter(w => w.source === 'workbook').length]));
const report = { workbook: 'Workbook of English for Information Technology (2016)', totalWorkbookEntries: rows.length, supplementalEntries: allWords.length - rows.length, lessons: counts, corrections: rows.filter(row => row.extractionNote).map(row => ({ lessonId: row.lessonId, term: row.term, page: row.page, note: row.extractionNote })) };
await fs.writeFile('src/data.js', '// Generated by scripts/build-vocabulary.mjs. See content/ for source extraction and translations.\nexport const units = ' + JSON.stringify(units, null, 2) + ';\nexport const words = units.flatMap(unit => unit.lessons.flatMap(lesson => lesson.words));\nexport const workbookWords = words.filter(word => word.source === "workbook");\nexport const wordById = Object.fromEntries(words.map(word => [word.id, word]));\n');
await fs.writeFile('content/coverage.json', JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report, null, 2));
